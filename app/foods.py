def search(q: str = "", limit: int = 60) -> list[dict]:
    """按名称包含匹配（忽略大小写与空格），空查询返回全部。"""
    q = (q or "").strip().lower().replace(" ", "")
    if not q:
        return FOODS[:limit]
    out = [f for f in FOODS if q in f["name"].lower().replace(" ", "")]
    return out[:limit]


def compute(food: dict, grams: float) -> dict:
    """按克数换算营养。"""
    k = max(0.0, float(grams or 0)) / 100.0
    return {
        "kcal": round(food["kcal"] * k, 1),
        "protein_g": round(food["p"] * k, 1),
        "carb_g": round(food["c"] * k, 1),
        "fat_g": round(food["f"] * k, 1),
    }
